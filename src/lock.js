// agent-xray.lock: a reviewable snapshot of what your agents will load and auto-run.
// Contains hashes of harness files, the hook/status-line/helper inventory (commands already redacted),
// MCP server definitions (names, package@version, env var NAMES only) — never secret values.
// `verify` re-scans and reports anything that changed, appeared or disappeared.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

export const LOCK_VERSION = 1;
export const LOCK_NAME = 'agent-xray.lock';

const sha = (buf) => 'sha256:' + crypto.createHash('sha256').update(buf).digest('hex');

/** Absolute path for a report file path ("~/…" or absolute). */
function absOf(p, home) { return p.startsWith('~/') || p === '~' ? path.join(home, p.slice(2)) : p; }

/** Key used in the lock: project files relative to the project ("./…"), user files as "~/…". */
function keyOf(p, project, home) {
  if (home && (p === '~' || p.startsWith('~/'))) { const a = absOf(p, home); if (project && (a === project || a.startsWith(project + path.sep))) p = a; }
  if (project && path.isAbsolute(p) && (p === project || p.startsWith(project + path.sep))) return './' + path.relative(project, p).split(path.sep).join('/');
  return p.split(path.sep).join('/');
}

function sortObj(o) { return Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]])); }

/** Build lock data from a scan report. opts: { home, project, user: include user-level files }. */
export function buildLock(report, { home, project, user = false } = {}) {
  const inScope = (scope) => scope === 'project' || (user && scope !== 'project');
  const files = {};
  for (const f of report.files || []) {
    if (!inScope(f.scope)) continue;
    let buf;
    try { buf = fs.readFileSync(absOf(f.path, home)); } catch { continue; }
    files[keyOf(f.path, project, home)] = sha(Buffer.from(buf.toString('utf8').replace(/\r\n/g, '\n'), 'utf8'));
  }
  const autorun = (report.autorun || []).filter((a) => inScope(a.scope)).map((a) => ({
    file: keyOf(a.file, project, home), kind: a.kind, event: a.event || null, matcher: a.matcher || null,
    run: a.command || a.url || null, agents: [...a.agents].sort(),
  })).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));
  const servers = {};
  for (const s of report.servers || []) {
    const inProj = (p) => { const a = absOf(p, home || ''); return !!project && (a === project || a.startsWith(project + path.sep)); };
    const fs_ = (s.files || []).filter((p) => user || inProj(p));
    if (!fs_.length) continue;
    servers[s.name] = sortObj({
      transport: s.transport, command: s.command || null, package: s.package || null, pinned: !!s.pinned,
      url: s.url || null, envKeys: [...(s.envKeys || [])].sort(), files: fs_.map((p) => keyOf(p, project, home)).sort(), disabled: !!s.disabled,
    });
  }
  return { lockVersion: LOCK_VERSION, tool: 'agent-xray', version: report.version, scope: user ? 'project+user' : 'project', files: sortObj(files), autorun, mcpServers: sortObj(servers) };
}

export function serializeLock(lock, now = new Date()) {
  return JSON.stringify({ ...lock, createdAt: now.toISOString(), note: 'Generated by `npx @non-zero_ai/agent-xray lock`. Review changes to this file like code. No secret values are stored here.' }, null, 2) + '\n';
}

export function readLock(file) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (data?.tool !== 'agent-xray' || data.lockVersion !== LOCK_VERSION) throw new Error(`${file} is not an agent-xray lock (version ${LOCK_VERSION})`);
  return data;
}

/** Compare a stored lock with a fresh one. Returns [{ kind: added|removed|changed, what, key, detail }]. */
export function diffLock(old, cur) {
  const out = [];
  for (const k of Object.keys(cur.files)) {
    if (!(k in old.files)) out.push({ kind: 'added', what: 'file', key: k, detail: 'new harness/instruction file' });
    else if (old.files[k] !== cur.files[k]) out.push({ kind: 'changed', what: 'file', key: k, detail: 'content changed' });
  }
  for (const k of Object.keys(old.files)) if (!(k in cur.files)) out.push({ kind: 'removed', what: 'file', key: k, detail: 'file is gone' });
  const id = (a) => JSON.stringify([a.file, a.kind, a.event, a.matcher, a.run]);
  const oldA = new Set((old.autorun || []).map(id)), curA = new Set((cur.autorun || []).map(id));
  for (const a of cur.autorun || []) if (!oldA.has(id(a))) out.push({ kind: 'added', what: a.kind, key: a.file, detail: `${a.event ? a.event + ': ' : ''}${a.run || '(no command)'}` });
  for (const a of old.autorun || []) if (!curA.has(id(a))) out.push({ kind: 'removed', what: a.kind, key: a.file, detail: `${a.event ? a.event + ': ' : ''}${a.run || '(no command)'}` });
  const os_ = old.mcpServers || {}, cs = cur.mcpServers || {};
  for (const n of Object.keys(cs)) {
    if (!(n in os_)) out.push({ kind: 'added', what: 'mcp-server', key: n, detail: cs[n].package || cs[n].url || cs[n].command || '' });
    else if (JSON.stringify(os_[n]) !== JSON.stringify(cs[n])) {
      const ch = Object.keys(cs[n]).filter((k) => JSON.stringify(cs[n][k]) !== JSON.stringify(os_[n][k]));
      out.push({ kind: 'changed', what: 'mcp-server', key: n, detail: `changed: ${ch.join(', ')}` + (ch.includes('package') ? ` (${os_[n].package || '-'} → ${cs[n].package || '-'})` : '') });
    }
  }
  for (const n of Object.keys(os_)) if (!(n in cs)) out.push({ kind: 'removed', what: 'mcp-server', key: n, detail: 'server definition is gone' });
  return out;
}

/** Turn drift into report findings (category lock-drift). Additions of auto-run/servers are high, the rest medium. */
export function driftFindings(drift, lockFile) {
  return drift.map((d) => ({
    id: 'lock.drift', category: 'lock-drift',
    severity: d.kind === 'added' && d.what !== 'file' ? 'high' : 'medium',
    agents: ['shared'],
    title: `${d.what === 'file' ? 'Harness file' : d.what === 'mcp-server' ? 'MCP server' : 'Auto-run ' + d.what} ${d.kind} since agent-xray.lock: ${d.key}`,
    detail: `${d.detail}. Locked in ${lockFile}.`,
    file: d.what === 'mcp-server' ? null : d.key, line: null, evidence: d.detail.slice(0, 160), fix: 'Review the change; if intended, run `npx @non-zero_ai/agent-xray lock` and commit the lock.',
  }));
}
